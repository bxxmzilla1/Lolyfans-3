/**
 * Pre-render the PPV badge text assets (price glyphs + Lolyfans wordmark)
 * into base64 PNGs. Serverless hosts have no fonts, so SVG <text> silently
 * renders nothing there — these assets are rendered once on a dev machine
 * (which has fonts) and committed.
 *
 * Run: node scripts/gen-badge-assets.mjs
 * Output: src/lib/badgeAssets.ts
 */
import sharp from "sharp";
import { writeFileSync } from "fs";

const CANVAS_H = 220;
const FONT = `"Segoe UI", Arial, sans-serif`;

/** Tight bounding box of non-transparent pixels. */
async function bbox(png) {
  const { data, info } = await sharp(png)
    .raw()
    .toBuffer({ resolveWithObject: true });
  let minX = info.width, minY = info.height, maxX = -1, maxY = -1;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      const a = data[(y * info.width + x) * 4 + 3];
      if (a > 8) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }
  if (maxX < 0) throw new Error("empty render");
  return { left: minX, top: minY, width: maxX - minX + 1, height: maxY - minY + 1 };
}

async function renderGlyph(char) {
  const esc = char === "$" ? "$" : char;
  const svg = `<svg width="300" height="${CANVAS_H}" xmlns="http://www.w3.org/2000/svg">
    <text x="150" y="170" text-anchor="middle" font-family='${FONT}' font-size="170" font-weight="800" fill="#ffffff">${esc}</text>
  </svg>`;
  const png = await sharp(Buffer.from(svg)).png().toBuffer();
  const box = await bbox(png);
  const cropped = await sharp(png).extract(box).png().toBuffer();
  return { b64: cropped.toString("base64"), w: box.width, h: box.height, top: box.top };
}

async function renderWordmark() {
  // White wordmark with a soft dark shadow so it reads on any blurred media.
  const svg = `<svg width="1000" height="260" xmlns="http://www.w3.org/2000/svg">
    <defs>
      <filter id="s" x="-20%" y="-20%" width="140%" height="140%">
        <feDropShadow dx="0" dy="3" stdDeviation="7" flood-color="#000" flood-opacity="0.55"/>
      </filter>
    </defs>
    <text x="24" y="170" font-family='${FONT}' font-size="130" font-weight="800"
          fill="#ffffff" filter="url(#s)">LolyFans</text>
  </svg>`;
  const png = await sharp(Buffer.from(svg)).png().toBuffer();
  const box = await bbox(png);
  const cropped = await sharp(png).extract(box).png().toBuffer();
  return { b64: cropped.toString("base64"), w: box.width, h: box.height };
}

const chars = "$0123456789.";
const glyphs = {};
for (const c of chars) {
  glyphs[c] = await renderGlyph(c);
  console.log("glyph", c, glyphs[c].w, "x", glyphs[c].h, "top", glyphs[c].top);
}
const wordmark = await renderWordmark();
console.log("wordmark", wordmark.w, "x", wordmark.h);

const ts = `/**
 * AUTO-GENERATED by scripts/gen-badge-assets.mjs — do not edit by hand.
 * Pre-rendered white text PNGs (base64) for the Telegram PPV teaser badge.
 * Serverless hosts have no fonts, so text must ship as pixels.
 */

export type Glyph = { b64: string; w: number; h: number; top: number };

/** Height of the canvas the glyphs were rendered on (baseline-aligned). */
export const GLYPH_CANVAS_H = ${CANVAS_H};

export const GLYPHS: Record<string, Glyph> = ${JSON.stringify(glyphs, null, 2)};

export const WORDMARK = ${JSON.stringify(wordmark, null, 2)};
`;

writeFileSync("src/lib/badgeAssets.ts", ts);
console.log("wrote src/lib/badgeAssets.ts");
